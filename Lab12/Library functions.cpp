#include <iostream>
#include <cmath>
using namespace std;
int main()
{
	int n;
	cout<<"Enter a number to apply library functions on it: ";
	cin>>n;
	cout<<"Square root: "<<sqrt(n)<<endl;
	cout<<"Absolute value: "<<abs(n)<<endl;
	cout<<"sin: "<<sin(n)<<endl;
	cout<<"cos: "<<cos(n)<<endl;
	cout<<"Power 3: "<<pow(n,3)<<endl;
	
	
	
	
	
	return 0;
}
